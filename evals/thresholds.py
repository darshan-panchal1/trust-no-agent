"""Article V: every pass threshold lives in `evals/thresholds.yaml`, and nowhere else.

A missing file or a missing metric is a loud error — never a default, never an environment
override. The file is generated by `calibrate` (FR-037/FR-039), never hand-written; the
`justification` field is what makes a hand-edit visible in review.
"""

from __future__ import annotations

from pathlib import Path

import yaml
from pydantic import BaseModel

THRESHOLDS_PATH = Path(__file__).resolve().parent / "thresholds.yaml"
CALIBRATE_COMMAND = "uv run python -m evals.cli calibrate"


class Threshold(BaseModel):
    """One metric's gate, carrying the observed scores that bracket it (FR-037)."""

    value: float
    justification: str
    v1_observed: float
    v2_observed: float


class Thresholds(BaseModel):
    # FR-037 keeps FR-043's tolerance in this same file so Article V's one-file rule holds.
    # Same per-value+justification shape as each Threshold entry: a number with no
    # justification is a number you guessed.
    comparison_tolerance: float
    comparison_tolerance_justification: str
    metrics: dict[str, Threshold]


def load_thresholds(path: Path | None = None) -> Thresholds:
    """Resolves `THRESHOLDS_PATH` at call time, so a test can point it at a fixture."""
    resolved = THRESHOLDS_PATH if path is None else path
    if not resolved.exists():
        raise FileNotFoundError(
            f"no thresholds file at {resolved}. Generate it with `{CALIBRATE_COMMAND}` — "
            f"Article V forbids defaulting a threshold that was never calibrated."
        )
    return Thresholds.model_validate(yaml.safe_load(resolved.read_text()))


def threshold_for(metric: str, path: Path | None = None) -> float:
    """The gate for one metric. A missing key is loud: no `.get`, no `or 0.7`."""
    thresholds = load_thresholds(path)
    if metric not in thresholds.metrics:
        raise KeyError(
            f"no threshold for {metric!r}. Every gated metric needs one — "
            f"regenerate with `{CALIBRATE_COMMAND}`."
        )
    return thresholds.metrics[metric].value
